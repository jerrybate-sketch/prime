"""SDK acceptance check using real Linux shell processes and procfs.

The platform batch response is simulated from the exit files, matching the
documented exit-file-only VM endpoint. Launch and liveness shell commands are
executed unchanged. This is a Linux protocol test, NOT a live Prime provider test.
"""

from __future__ import annotations

import argparse
import asyncio
import hashlib
import json
import os
import platform
import shlex
import shutil
import subprocess
import sys
import time
import uuid
from pathlib import Path

PARSER = argparse.ArgumentParser()
PARSER.add_argument("--sdk-source", type=Path, required=True)
PARSER.add_argument("--deps", type=Path, help="Optional local dependency directory")
PARSER.add_argument("--shell", type=Path, help="Bash executable (defaults to Git Bash on Windows)")
PARSER.add_argument("--output", type=Path, required=True)
PARSER.add_argument("--expect", choices=("baseline", "fixed"), required=True)
ARGS = PARSER.parse_args()
if platform.system() != "Linux":
    PARSER.error("This validation requires real Linux and /proc, not Windows/MSYS.")
if not Path("/proc/self/cmdline").is_file():
    PARSER.error("Linux procfs is required for wrapper identity checks.")
sys.path.insert(0, str(ARGS.sdk_source.resolve()))
if ARGS.deps:
    sys.path.insert(1, str(ARGS.deps.resolve()))

from prime_sandboxes import AsyncSandboxClient  # noqa: E402
from prime_sandboxes.models import CommandResponse, ReadFileResponse  # noqa: E402
from prime_sandboxes.sandbox import _canonical_background_job  # noqa: E402

BASH = ARGS.shell or (
    Path(os.environ["LOCALAPPDATA"]) / "Programs/Git/bin/bash.exe"
    if os.name == "nt"
    else Path(shutil.which("bash") or "/bin/bash")
)
KERNEL = subprocess.check_output([str(BASH), "-c", "uname -s"], text=True).strip()
TEMP_ROOT = (
    Path(subprocess.check_output([str(BASH), "-c", "cygpath -w /tmp"], text=True).strip()).resolve()
    if os.name == "nt"
    else Path("/tmp")
)


def guest_path(path: str) -> Path:
    if not path.startswith("/tmp/job_"):
        raise AssertionError(f"Unexpected guest path: {path}")
    resolved = (TEMP_ROOT / path.removeprefix("/tmp/")).resolve()
    if not resolved.is_relative_to(TEMP_ROOT):
        raise AssertionError("Guest path escaped isolated job files")
    return resolved


class LocalTransport:
    def __init__(self) -> None:
        self.batch_calls = 0
        self.probe_calls = 0
        self.active_probes = 0
        self.peak_probes = 0
        self.jobs = []
        self.job_names = {}
        self.probe_records = []
        self.pending_observations = []
        self.gates = {
            name: guest_path(f"/tmp/job_{uuid.uuid4().hex[:8]}.release")
            for name in ("live-slow", "legacy-no-pid")
        }

    def gated_command(self, name):
        gate = shlex.quote(str(self.gates[name]))
        # The loop also bounds orphan lifetime if this diagnostic is interrupted.
        return (
            f"n=0; while [ ! -e {gate} ] && [ $n -lt 250 ]; "
            f"do n=$((n+1)); sleep 0.02; done; test -e {gate} || exit 91; printf {name}"
        )

    def observe_pending(self, job_id, kind):
        name = self.job_names.get(job_id)
        if name not in self.gates:
            return
        pid_exists = guest_path(f"/tmp/job_{job_id}.launch/pid").exists()
        self.pending_observations.append(
            {"scenario": name, "job_id": job_id, "kind": kind, "pid_exists": pid_exists}
        )
        if (ARGS.expect == "baseline" and kind == "batch") or kind == "probe":
            # A healthy gated job cannot complete before its pending observation.
            self.gates[name].touch()

    async def request(self, method, path, **kwargs):
        assert (method, path) == ("POST", "/sandbox/background-jobs/status:batchGet")
        self.batch_calls += 1
        statuses = []
        for item in kwargs["json"]["jobs"]:
            file = guest_path(f"/tmp/job_{item['job_id']}.exit")
            content = file.read_text().strip() if file.exists() else ""
            statuses.append(
                {**item, "completed": bool(content), "exit_code": int(content) if content else None}
            )
            if not content:
                self.observe_pending(item["job_id"], "batch")
        return {"statuses": statuses, "errors": []}

    async def execute(self, sandbox_id, command, **kwargs):
        # No network, no arbitrary user input: command is generated by the SDK.
        probe = "grep" in command
        if probe:
            self.probe_calls += 1
            self.active_probes += 1
            self.peak_probes = max(self.peak_probes, self.active_probes)
        process = await asyncio.create_subprocess_exec(
            str(BASH),
            "-c",
            command,
            stdout=asyncio.subprocess.PIPE,
            stderr=asyncio.subprocess.PIPE,
        )
        try:
            out, err = await asyncio.wait_for(process.communicate(), timeout=10)
        except BaseException:
            if process.returncode is None:
                process.kill()
                await process.wait()
            raise
        finally:
            if probe:
                self.active_probes -= 1
        result = CommandResponse(
            stdout=out.decode(errors="replace"),
            stderr=err.decode(errors="replace"),
            exit_code=process.returncode,
        )
        if probe:
            self.probe_records.append(
                {
                    "sandbox_id": sandbox_id,
                    "stdout": result.stdout,
                    "stderr": result.stderr,
                    "exit_code": result.exit_code,
                }
            )
            for line in result.stdout.splitlines():
                job_id, separator, status = line.partition(" ")
                if separator and not status:
                    self.observe_pending(job_id, "probe")
        return result

    async def read(self, sandbox_id, path, **kwargs):
        file = guest_path(path)
        data = file.read_bytes() if file.exists() else b""
        offset = kwargs.get("offset", 0)
        length = kwargs.get("length", len(data))
        start = max(0, len(data) + offset) if offset < 0 else offset
        return ReadFileResponse(
            content=data[start : start + length].decode(errors="replace"),
            size=len(data),
            truncated=start > 0,
        )

    async def aclose(self):
        pass

    def cleanup(self):
        # Delete only the exact artifacts of SDK-generated job handles recorded
        # in this run; no wildcard/process-wide cleanup and no recursive delete.
        for job in self.jobs:
            for path in (
                job.stdout_log_file,
                job.stderr_log_file,
                job.exit_file,
                f"/tmp/job_{job.job_id}.launch/pid",
            ):
                guest_path(path).unlink(missing_ok=True)
            launch_dir = guest_path(f"/tmp/job_{job.job_id}.launch")
            if launch_dir.exists():
                launch_dir.rmdir()
        for gate in self.gates.values():
            gate.unlink(missing_ok=True)


async def run():
    transport = LocalTransport()
    client = AsyncSandboxClient(api_key="local-acceptance-no-network")
    await client.client.aclose()
    client.client = transport
    client.execute_command = transport.execute
    client.read_file = transport.read
    original_start = client.start_background_job
    slow_command = transport.gated_command("live-slow")

    async def start(*args, **kwargs):
        if args[1] == "legacy-no-pid":
            job = _canonical_background_job(args[0], uuid.uuid4().hex[:8])
            # Model the pre-acknowledgement protocol: real background shell and
            # exit/output files, but no launch/pid metadata. This healthy job must
            # not become a false infrastructure failure after an SDK update.
            body = (
                f"({transport.gated_command('legacy-no-pid')}) "
                f"> {shlex.quote(job.stdout_log_file)} "
                f"2> {shlex.quote(job.stderr_log_file)}; echo $? > {shlex.quote(job.exit_file)}"
            )
            await transport.execute(
                args[0], f"nohup sh -c {shlex.quote(body)} < /dev/null > /dev/null 2>&1 &"
            )
        else:
            job = await original_start(*args, **kwargs)
        transport.jobs.append(job)
        if args[1] == "legacy-no-pid":
            transport.job_names[job.job_id] = "legacy-no-pid"
        elif args[1] == slow_command:
            transport.job_names[job.job_id] = "live-slow"
        return job

    async def context(*args, **kwargs):
        return {"status": "RUNNING", "error_type": None, "error_message": None}

    client.start_background_job = start
    client._get_sandbox_error_context = context
    scenarios = [
        ("normal-zero", "printf normal-zero", 0),
        ("normal-nonzero", "printf normal-nonzero; exit 3", 3),
        ("live-slow", slow_command, 0),
        ("legacy-no-pid", "legacy-no-pid", 0),
        ("lost-wrapper", "kill -9 $$", None),
    ]

    async def one(name, command, expected_exit):
        started = time.monotonic()
        try:
            result = await client.run_background_job(
                "local-vm",
                command,
                timeout=2,
                poll_interval=0.02,
            )
            return {
                "scenario": name,
                "kind": "completed",
                "exit_code": result.exit_code,
                "stdout": result.stdout,
                "expected_exit": expected_exit,
                "elapsed_seconds": round(time.monotonic() - started, 4),
            }
        except Exception as exc:
            return {
                "scenario": name,
                "kind": type(exc).__name__,
                "message": str(exc),
                "elapsed_seconds": round(time.monotonic() - started, 4),
            }

    try:
        results = await asyncio.wait_for(
            asyncio.gather(*(one(*scenario) for scenario in scenarios)),
            timeout=15,
        )
        good = results[:-1]
        assert all(
            r["kind"] == "completed"
            and r["exit_code"] == r["expected_exit"]
            and r["stdout"] == r["scenario"]
            for r in good
        ), results
        lost = results[-1]
        expected_kind = "CommandTimeoutError" if ARGS.expect == "baseline" else "APIError"
        assert lost["kind"] == expected_kind, results
        if ARGS.expect == "fixed":
            assert "without recording an exit code" in lost["message"], lost
        observed_kind = "probe" if ARGS.expect == "fixed" else "batch"
        for name in ("live-slow", "legacy-no-pid"):
            observations = [
                item
                for item in transport.pending_observations
                if item["scenario"] == name and item["kind"] == observed_kind
            ]
            assert observations, (name, transport.pending_observations)
            if name == "legacy-no-pid":
                assert all(not item["pid_exists"] for item in observations), observations
        report = {
            "state": "passed",
            "expectation": ARGS.expect,
            "sdk_source": str(ARGS.sdk_source.resolve()),
            "sdk_sandbox_sha256": hashlib.sha256(
                (ARGS.sdk_source / "prime_sandboxes/sandbox.py").read_bytes()
            ).hexdigest(),
            "acceptance_script_sha256": hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),
            "environment": f"{KERNEL}; real local shell, simulated exit-only batch API",
            "cloud_sandbox_exercised": False,
            "limitations": [
                "Local OS proc semantics are not provider validation",
                "No production provider behavior, billed savings or latency claim",
            ],
            "results": results,
            "batch_calls": transport.batch_calls,
            "probe_calls": transport.probe_calls,
            "peak_probes": transport.peak_probes,
            "probe_records": transport.probe_records,
            "pending_observations": transport.pending_observations,
            "scenario_job_ids": {name: job_id for job_id, name in transport.job_names.items()},
        }
        ARGS.output.parent.mkdir(parents=True, exist_ok=True)
        ARGS.output.write_text(json.dumps(report, indent=2) + "\n", encoding="utf-8")
        print(json.dumps({k: v for k, v in report.items() if k != "probe_records"}, indent=2))
    finally:
        for gate in transport.gates.values():
            gate.touch()
        # Release diagnostic jobs and let their bounded wrappers finish before
        # removing their exact artifacts, including on an assertion failure.
        for _ in range(100):
            pending = [
                job
                for job in transport.jobs
                if job.job_id in transport.job_names and not guest_path(job.exit_file).exists()
            ]
            if not pending:
                break
            await asyncio.sleep(0.02)
        await client.aclose()
        transport.cleanup()


if __name__ == "__main__":
    asyncio.run(run())
